"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const html=fs.readFileSync("index.html","utf8");
const start=html.indexOf("const bangerPlayByPlayInflight=new Map();");
const end=html.indexOf("let czTimer=null,czToken=0;",start);
assert(start>=0&&end>start,"shared play-by-play loader must exist");
assert(html.includes("const d=await bangerGetPlayByPlay(id);"),"LIVE consumers must use shared loader");
assert.equal((html.match(/const d=await bangerGetPlayByPlay\(id\);/g)||[]).length,2,"timeline and commentary must both use shared loader");
let calls=0,release;
let response=new Promise(resolve=>{release=resolve});
let rejectRequest;
const sandbox={Map,encodeURIComponent,AbortSignal:{timeout:()=>({})},fetch:async url=>{calls++;return response}};
vm.createContext(sandbox);
vm.runInContext(html.slice(start,end)+"\nthis.load=bangerGetPlayByPlay;",sandbox);
(async()=>{
 const a=sandbox.load(100),b=sandbox.load(100);
 assert.equal(calls,1,"simultaneous requests for same game must deduplicate");
 release({ok:true,json:async()=>({plays:[{eventId:1}]})});
 assert.equal((await a).plays[0].eventId,1);
 assert.equal((await b).plays[0].eventId,1);
 await Promise.resolve();
 response=Promise.resolve({ok:true,json:async()=>({plays:[{eventId:2}]})});
 assert.equal((await sandbox.load(100)).plays[0].eventId,2,"next polling cycle must get fresh data");
 assert.equal(calls,2,"sequential poll must fetch again");
 response=Promise.resolve({ok:true,json:async()=>({plays:[{eventId:3}]})});
 assert.equal((await sandbox.load(200)).plays[0].eventId,3);
 assert.equal(calls,3,"different game must use separate request");
 response=Promise.resolve({ok:false,status:503});
 await assert.rejects(sandbox.load(300),/HTTP 503/);
 await Promise.resolve();
 response=Promise.resolve({ok:true,json:async()=>({plays:[]})});
 await sandbox.load(300);
 assert.equal(calls,5,"failed request must not remain cached");
 assert(html.includes("if(!bangerIsCurrentDetail(id,'bangerGameTimeline',root))return;"),"timeline must guard against stale game");
 assert(html.includes("if(token!==czToken||!$('commentaryFeed'))return;"),"commentary must guard against stale game");
 console.log("STAB-03 shared play-by-play regression tests passed");
})().catch(e=>{console.error(e);process.exitCode=1});
