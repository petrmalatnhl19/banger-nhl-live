"use strict";
const assert=require("node:assert/strict");
const {inspectGame}=require("./core43_end_to_end_readiness.cjs");
const prediction={game_id:42,away_team:"DAL",home_team:"NJD",core41_predicted_at:"2026-11-09T12:00:00Z"};
const schedule={game_id:42,away_team:"DAL",home_team:"NJD",kickoff_at:"2026-11-09T20:00:00Z"};
const input={prediction,schedule,goalies:[{game_id:42,team_code:"DAL",goalie_name:"Example Goalie",observed_status:"projected",observed_at:"2026-11-09T11:00:00Z"}]};
const result=inspectGame(input);
assert.equal(result.available,true);
assert.equal(result.production,false);
assert.equal(result.persistable,false);
assert.equal(result.sides.away.goalie.status,"projected");
assert.equal(result.sides.home.goalie.status,"unavailable");
assert.equal(result.sides.away.gsax.available,false);
assert.equal(result.readyForCalibratedForecast,false);
assert.equal(inspectGame({...input,goalies:[{...input.goalies[0],observed_at:"2026-11-09T13:00:00Z"}]}).sides.away.goalie.status,"unavailable");
assert.equal(inspectGame({...input,gsax:[{game_id:42,team_code:"DAL",fetched_at:"2026-11-09T13:00:00Z",gsax_per_100_shots:2,shots_against:80}]}).sides.away.gsax.reason,"late_or_invalid_gsax_snapshot");
assert.equal(inspectGame({...input,gsax:[{game_id:42,team_code:"DAL",fetched_at:"2026-11-09T11:00:00Z",gsax_per_100_shots:2,shots_against:80}]}).sides.away.gsax.available,true);
assert.equal(inspectGame({...input,schedule:{...schedule,away_team:"NYR"}}).reason,"team_mismatch");
assert.equal(inspectGame({...input,prediction:{...prediction,core41_predicted_at:"2026-11-09T21:00:00Z"}}).reason,"invalid_frozen_prediction_time");
console.log("CORE 4.3 end-to-end readiness tests passed");
