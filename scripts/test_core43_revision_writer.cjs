const assert=require("node:assert/strict");
const {buildRow,writeRow}=require("./write_core43_revision.cjs");
const prediction={game_id:123,away_team:"DAL",home_team:"NJD",core41_predicted_at:"2026-11-09T10:00:00Z"};
const schedule={game_id:123,away_team:"DAL",home_team:"NJD",kickoff_at:"2026-11-09T20:00:00Z"};
const evidence=["DAL","NJD"].map((team,i)=>({game_id:123,team_code:team,goalie_id:String(10000+i),evidence_status:"confirmed",source_name:"Verified report",source_url:"https://example.org/report",source_published_at:"2026-11-09T12:00:00Z",verified_at:"2026-11-09T13:00:00Z"}));
const payload={prediction,schedule,evidence,asOf:"2026-11-09T14:00:00Z",predictedAway:2.75,predictedHome:3.1,inputSnapshot:{modelVersion:"test"}};
const row=buildRow(payload);
assert.equal(row.revision_kind,"pregame");
assert.equal(row.away_goalie_id,"10000");
assert.equal(row.source_prediction_at,prediction.core41_predicted_at);
assert.equal(prediction.core41_predicted_at,"2026-11-09T10:00:00Z");
assert.throws(()=>buildRow({...payload,predictedAway:"2.75"}),/invalid_expected_goals/);
assert.throws(()=>buildRow({...payload,asOf:"2026-11-09T12:30:00Z"}),/revision_rejected/);
assert.throws(()=>buildRow({...payload,inputSnapshot:null}),/missing_input_snapshot/);
