"use strict";
const assert=require("node:assert/strict");
const {computeCore43}=require("./core43_research_engine_v0.cjs");
const team=(observedAt="2026-11-09T17:00:00Z")=>({observedAt,shotShare:.5,xgShare:.5,ppRate:.2,pkRate:.8,restDays:2,goalieGSAx60:0});
const payload=()=>({gameId:"game-1",awayTeam:"DAL",homeTeam:"UTA",kickoffAt:"2026-11-09T20:00:00Z",asOf:"2026-11-09T18:00:00Z",inputs:{baseline:{gameId:"game-1",awayGoals:2.8,homeGoals:2.6,observedAt:"2026-11-09T17:00:00Z"},away:team(),home:team()}});
const r=computeCore43(payload());
assert.equal(r.expectedAwayGoals,2.8);
assert.equal(r.expectedHomeGoals,2.6);
assert.equal(r.persistable,false);
assert.equal(r.calibrated,false);
assert.equal(r.production,false);
assert.equal(r.model,"core43");
assert.deepEqual(computeCore43(payload()),r);
const p=payload();p.inputs.away.xgShare=.7;
assert.ok(computeCore43(p).expectedAwayGoals>r.expectedAwayGoals);
const future=payload();future.inputs.home.observedAt="2026-11-09T19:00:00Z";
assert.throws(()=>computeCore43(future),/future_home_inputs/);
const late=payload();late.asOf=late.kickoffAt;
assert.throws(()=>computeCore43(late),/not_pregame/);
const wrong=payload();wrong.inputs.baseline.gameId="other";
assert.throws(()=>computeCore43(wrong),/baseline_game_mismatch/);
const invalid=payload();invalid.inputs.away.goalieGSAx60=NaN;
assert.throws(()=>computeCore43(invalid),/invalid_away_goalie_gsax60/);
const {buildComputedRevision}=require("./core43_computed_revision_adapter.cjs");
assert.throws(()=>buildComputedRevision({prediction:{game_id:"game-1"},asOf:r.computedAt,model:"core43",computed:r}),/nonpersistable_forecast/);
console.log("CORE 4.3 research engine v0 tests passed");
