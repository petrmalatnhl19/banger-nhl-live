"use strict";
const assert=require("node:assert/strict");
const {calculate}=require("./core43_verified_dashboard.js");
const schedule=(id,home="UTA")=>({game_id:id,away_team:"DAL",home_team:home,kickoff_at:"2026-11-09T20:00:00Z"});
const archive=(id,other={})=>({game_id:id,status:"final",away_team:"DAL",home_team:"UTA",actual_away:3,actual_home:2,core41_away:3.2,core41_home:2.1,core41_predicted_at:"2026-11-09T19:00:00Z",core42_away:2.1,core42_home:3.2,core42_predicted_at:"2026-11-09T19:00:00Z",...other});
let r=calculate([archive(1),archive(2,{core42_predicted_at:null})],[schedule(1),schedule(2)]);
assert.equal(r.core41.games,2);
assert.equal(r.core42.games,1);
assert.equal(r.core41.correct,2);
assert.equal(r.core42.correct,0);
assert.equal(r.pairedGames,1);
assert.equal(r.paired41.games,1);
assert.equal(r.paired42.games,1);
r=calculate([archive(1)],[schedule(1),schedule(1,"NYR")]);
assert.equal(r.core41.games,0);
r=calculate([archive(1,{core41_predicted_at:"2026-11-09T20:00:00Z"})],[schedule(1)]);
assert.equal(r.core41.games,0);
r=calculate([archive(1,{core41_away:2.5,core41_home:2.5})],[schedule(1)]);
assert.equal(r.core41.calls,0);
assert.equal(r.core41.games,1);
console.log("CORE verified dashboard tests passed");
