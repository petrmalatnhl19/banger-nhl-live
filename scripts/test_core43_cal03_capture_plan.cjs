"use strict";
const assert=require("node:assert/strict");
const {plan,COEFFICIENTS}=require("./core43_cal03_capture_plan.cjs");
const observations=[["DAL","Goalie A"],["NYR","Goalie B"]].map(([team_code,goalie_name])=>({game_id:42,team_code,goalie_name,observed_status:"projected",observed_at:"2026-11-09T14:00:00Z",source_snapshot_at:"2026-11-09T13:00:00Z"}));
const identities=[["DAL","goalie a","8471234"],["NYR","goalie b","8475678"]].map(([team_code,normalized_name,goalie_id])=>({team_code,normalized_name,goalie_id,observed_at:"2026-11-09T12:00:00Z"}));
const gsaxRows=[{playerId:"8471234",team:"DAL",situation:"all",xGoals:"52",goals:"49",ongoal:"600"},{playerId:"8475678",team:"NYR",situation:"all",xGoals:"40",goals:"42",ongoal:"500"}];
const payload={gameId:42,awayTeam:"DAL",homeTeam:"NYR",predictionAt:"2026-11-09T21:59:00Z",kickoffAt:"2026-11-09T23:00:00Z",baseline:{away:3,home:2.8,predictedAt:"2026-11-09T12:00:00Z"},observations,identities,gsaxRows,gsaxFetchedAt:"2026-11-09T21:30:00Z"};
const provenance={gsaxArchiveId:"archived-snapshot-1",baselineModel:"core42"};
const now="2026-11-09T22:00:00Z";
const input={payload,provenance,now};
const before=JSON.stringify(input);
const result=plan(input);
assert.equal(result.ready,true,JSON.stringify(result));
assert.equal(result.writeEnabled,false);
assert.equal(result.variants.length,4);
assert.deepEqual(result.variants.map(x=>x.record.coefficient),COEFFICIENTS);
assert.equal(result.variants[0].record.away,3);
assert.equal(result.variants[0].record.home,2.8);
assert.equal(new Set(result.variants.map(x=>x.sha256)).size,4);
assert.equal(result.variants.every(x=>x.record.production===false&&x.record.persistable===false),true);
assert.equal(JSON.stringify(input),before,"must not mutate input");
assert.equal(plan({...input,existing:result.variants.map(x=>x.key)}).uniqueVariants,0);
const retryPayload={...payload,predictionAt:"2026-11-09T21:59:30Z"};
const retry=plan({...input,payload:retryPayload,now:"2026-11-09T22:00:30Z",existing:result.variants.map(x=>x.key)});
assert.equal(retry.ready,true,JSON.stringify(retry));
assert.equal(retry.uniqueVariants,0,"retry must not produce duplicate variants when predictionAt changes");
assert.deepEqual(retry.variants.map(x=>x.key),result.variants.map(x=>x.key));
const legacyKeys=result.variants.map(x=>x.key.replace("23:00:00.000Z","23:00:00Z"));
const equivalentKickoff={...payload,kickoffAt:"2026-11-10T00:00:00+01:00"};
const equivalent=plan({...input,payload:equivalentKickoff,existing:legacyKeys});
assert.equal(equivalent.uniqueVariants,0,"equivalent kickoff timestamps must match legacy keys");
assert.deepEqual(equivalent.variants.map(x=>x.key),result.variants.map(x=>x.key));
assert.equal(plan({...input,payload:{...payload,kickoffAt:"2026-11-09T23:05:00Z"},existing:legacyKeys}).uniqueVariants,4);
assert.equal(plan({...input,now:"2026-11-09T21:45:00Z",payload:{...payload,predictionAt:"2026-11-09T21:44:00Z"}}).ready,true,"75m boundary included");
assert.equal(plan({...input,now:"2026-11-09T22:15:00Z",payload:{...payload,predictionAt:"2026-11-09T22:14:00Z"}}).ready,true,"45m boundary included");
assert.equal(plan({...input,now:"2026-11-09T22:15:01Z"}).reason,"outside_60m_window");
assert.equal(plan({...input,existing:"not-an-array"}).reason,"invalid_existing_keys");
assert.equal(plan({...input,now:"2026-11-09T21:30:00Z"}).reason,"outside_60m_window");
assert.equal(plan({...input,now:"2026-11-09T22:30:00Z"}).reason,"outside_60m_window");
assert.equal(plan({...input,payload:{...payload,gsaxFetchedAt:"2026-11-09T22:05:00Z"}}).ready,false);
assert.equal(plan({...input,payload:{...payload,baseline:{...payload.baseline,predictedAt:"2026-11-09T22:10:00Z"}}}).ready,false);
assert.equal(plan({...input,provenance:{baselineModel:"core42"}}).reason,"missing_provenance");
console.log("CORE43-CAL-03 dry-run planner tests passed");
