"use strict";
const assert=require("node:assert/strict");
const {reconcileIdentities:run}=require("./core43_rotowire_identity_reconcile.cjs");
const observations=[{game_id:42,team_code:"DAL",goalie_name:"Goalie A",observed_status:"confirmed",observed_at:"2026-11-09T14:00:00Z",source_snapshot_at:"2026-11-09T13:00:00Z"}];
const identities=[{team_code:"DAL",normalized_name:"goalie a",goalie_id:"8471234",observed_at:"2026-11-09T12:00:00Z"}];
const check=(o=observations,i=identities,asOf="2026-11-09T15:00:00Z")=>run({observations:o,identities:i,asOf})[0];
assert.equal(check().goalieId,"8471234");
assert.equal(check().verifiedStarter,false);
assert.equal(check().eligibleForPromotion,false);
assert.equal(check(observations,[]).reason,"identity_missing_asof");
assert.equal(check(observations,[...identities,{...identities[0],goalie_id:"8479999"}]).reason,"identity_ambiguous");
assert.equal(check(observations,[{...identities[0],observed_at:"2026-11-10T12:00:00Z"}]).reason,"identity_missing_asof");
assert.equal(check(observations,identities,"2026-11-09T13:30:00Z").reason,"invalid_or_late_observation");
assert.equal(check([{...observations[0],source_snapshot_at:"2026-11-09T16:00:00Z"}]).reason,"invalid_or_late_observation");
assert.equal(check([{...observations[0],observed_status:"projected"}]).goalieId,"8471234");
assert.equal(check([{...observations[0],observed_status:"projected"}]).verifiedStarter,false);
assert.equal(check([{...observations[0],goalie_name:"Goalie B"}]).identityResolved,false);
assert.throws(()=>run({observations,identities,asOf:"nonsense"}),/invalid_asof/);
console.log("CORE 4.3 as-of identity reconciliation tests passed");
