const assert=require("node:assert/strict");
const {prepareComputedArchiveBatch:run}=require("./core43_computed_archive_batch.cjs");
const asOf="2026-11-09T14:00:00Z";
const prediction={game_id:42,away_team:"DAL",home_team:"NJD",core41_predicted_at:"2026-11-09T10:00:00Z"};
const schedule={game_id:42,away_team:"DAL",home_team:"NJD",kickoff_at:"2026-11-09T20:00:00Z"};
const evidence=["DAL","NJD"].map((team,i)=>({game_id:42,team_code:team,goalie_id:String(10000+i),evidence_status:"confirmed",source_name:"Verified report",source_url:"https://example.org/report",source_published_at:"2026-11-09T12:00:00Z",verified_at:"2026-11-09T13:00:00Z"}));
const computed={gameId:42,model:"core41",computedAt:asOf,production:false,engineVersion:"test-v1",expectedAwayGoals:2.8,expectedHomeGoals:3.1,inputSnapshot:{asOf,source:"test"}};
const data={predictions:[prediction],schedules:[schedule],evidence,computed:[computed],asOf};
const ok=run(data);
assert.equal(ok.prepared,1);assert.equal(ok.persisted,false);assert.equal(ok.rows[0].away_goalie_id,"10000");
assert.equal(run({...data,existingRevisions:[ok.rows[0]]}).rejections[0].reason,"already_archived");
assert.equal(run({...data,computed:[]}).rejections[0].reason,"missing_computed_forecast");
assert.equal(run({...data,computed:[computed,computed]}).rejections[0].reason,"ambiguous_computed_forecast");
assert.equal(run({...data,schedules:[schedule,schedule]}).rejections[0].reason,"ambiguous_schedule");
assert.equal(run({...data,predictions:[prediction,prediction]}).rejections[0].reason,"duplicate_archive_prediction");
assert.equal(run({...data,evidence:[]}).prepared,0);
assert.equal(run({...data,computed:[{...computed,computedAt:"2026-11-09T15:00:00Z"}]}).prepared,0);
assert.throws(()=>run({...data,asOf:"invalid"}),/invalid_asof/);
console.log("CORE 4.3 computed archive batch tests passed");
