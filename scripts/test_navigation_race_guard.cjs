"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const html=fs.readFileSync("index.html","utf8");
const from=html.indexOf("let bangerStatsRequestId=0;");
const to=html.indexOf("function normalizeGoalieSavePct(",from);
assert(from>=0&&to>from,"stats function must exist");
const nodes=new Map();
for(const id of ["calendarBar","search","sort","content","status"])nodes.set(id,{classList:{add(){},remove(){}},innerHTML:"",textContent:"",value:""});
const S={tab:"",rows:[],expanded:false};
let pending=[];
const get=()=>new Promise((resolve,reject)=>pending.push({resolve,reject}));
const sandbox={S,$:id=>nodes.get(id),get,safe:x=>x,renderStats(){sandbox.renderCount++},renderCount:0,Math,Number,Set,Promise};
vm.createContext(sandbox);
vm.runInContext(html.slice(from,to),sandbox);
(async()=>{
 const old=sandbox.stats("skaters");
 S.tab="games";
 pending.shift().reject(new Error("old request failed"));
 await old;
 assert.equal(nodes.get("status").textContent,"Načítám kompletní žebříček NHL…","old error must not replace current screen");
 const first=sandbox.stats("skaters");
 const second=sandbox.stats("skaters");
 pending.shift().resolve({data:[{playerId:1}],total:1});
 await first;
 assert.equal(sandbox.renderCount,0,"older same-tab success must not render");
 pending.shift().resolve({data:[{playerId:2}],total:1});
 await second;
 assert.equal(sandbox.renderCount,1,"latest same-tab request should render");
 assert.equal(S.rows[0].playerId,2);
 const third=sandbox.stats("skaters");
 const fourth=sandbox.stats("skaters");
 pending.shift().reject(new Error("stale"));
 await third;
 assert.equal(nodes.get("status").textContent,"Načítám kompletní žebříček NHL…","old same-tab failure must not overwrite new screen");
 pending.shift().resolve({data:[],total:0});
 await fourth;
 const news=html.slice(html.indexOf("let bangerNewsPageRequestId=0;"),html.indexOf("const ADV_REPORTS="));
 assert(news.includes("pageRequestId!==bangerNewsPageRequestId||requestId!==drawRequestId"),"news success must check page and refresh generation");
 assert(news.includes("pageRequestId===bangerNewsPageRequestId&&requestId===drawRequestId"),"news error must check page and refresh generation");
 console.log("STAB-04.1 navigation race regression tests passed");
})().catch(e=>{console.error(e);process.exitCode=1});
