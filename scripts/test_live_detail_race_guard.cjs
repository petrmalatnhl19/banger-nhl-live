"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const html=fs.readFileSync("index.html","utf8");
const begin=html.indexOf("let bangerDetailRequestId=0;");
const end=html.indexOf("async function detail(",begin);
assert(begin>=0&&end>begin,"LIVE detail request guard must exist");
const nodes={boxscoreContent:{},bangerGameTimeline:{}};
let hidden=false;
const sandbox={$:id=>id==="liveArena"?{classList:{contains:()=>hidden}}:nodes[id]};
vm.createContext(sandbox);
vm.runInContext(html.slice(begin,end)+"\nthis.setGame=id=>bangerActiveDetailGameId=id;this.isCurrent=bangerIsCurrentDetail;",sandbox);
sandbox.setGame("111");
const oldBox=nodes.boxscoreContent,oldTimeline=nodes.bangerGameTimeline;
assert.equal(sandbox.isCurrent(111,"boxscoreContent",oldBox),true);
assert.equal(sandbox.isCurrent(111,"bangerGameTimeline",oldTimeline),true);
sandbox.setGame("222");
assert.equal(sandbox.isCurrent(111,"boxscoreContent",oldBox),false,"old game's boxscore must be rejected");
assert.equal(sandbox.isCurrent(111,"bangerGameTimeline",oldTimeline),false,"old game's timeline must be rejected");
nodes.boxscoreContent={};
assert.equal(sandbox.isCurrent(222,"boxscoreContent",oldBox),false,"replaced panel must reject late responses");
hidden=true;
assert.equal(sandbox.isCurrent(222,"boxscoreContent",nodes.boxscoreContent),false,"closed modal must reject late responses");
assert(html.includes("if(!bangerIsCurrentDetail(id,'boxscoreContent',root))return;"),"boxscore must check after fetch");
assert(html.includes("if(!bangerIsCurrentDetail(id,'bangerGameTimeline',root))return;"),"timeline must check after fetch");
assert(html.includes("bangerActiveDetailGameId=null;++czToken;"),"closing detail must invalidate commentary");
console.log("STAB-02 LIVE detail stale response regression tests passed");
