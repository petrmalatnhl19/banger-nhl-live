"use strict";
const assert=require("node:assert/strict");
const {renderModel,DEFAULT_MODE}=require("./security120-tv-ui-gate.cjs");
const {VERSION}=require("./security118-tv-freshness.cjs");
assert.equal(DEFAULT_MODE,"legacy");
assert.deepEqual(renderModel(),{mode:"legacy",enabled:false,rows:[],message:null});
assert.equal(renderModel({mode:"public",snapshot:{}}).enabled,false);
const now=Date.parse("2026-11-17T10:00:00Z");
const metadata=[{game_id:2026020335,game_date:"2026-11-17",away_team:"EDM",home_team:"FLA",status:"pending",secret:"never"}];
const predictions=[{game_id:2026020335,core42_away:2,core42_home:3,core43_away:2,core43_home:4,core43_preview_away:2,core43_preview_home:4,away_gsax_per100:null,home_gsax_per100:null,internal:"never"}];
const snapshot={metadata,predictions,metadataAsOf:"2026-11-17T09:59:00Z",predictionsAsOf:"2026-11-17T09:59:00Z",metadataVersion:VERSION,predictionsVersion:VERSION,now};
const ready=renderModel({mode:"public-preview",snapshot});
assert.equal(ready.state,"ready");
assert.equal(ready.rows.length,1);
assert.equal(ready.rows[0].core42_away,2);
assert.equal(ready.rows[0].core43_home,4);
assert.equal(ready.rows[0].away_gsax_per100,null);
assert.equal(JSON.stringify(ready).includes("secret"),false);
assert.equal(JSON.stringify(ready).includes("internal"),false);
const stale=renderModel({mode:"public-preview",snapshot:{...snapshot,now:now+3600000}});
assert.equal(stale.state,"stale");assert.equal(stale.rows.length,0);
const missing=renderModel({mode:"public-preview",snapshot:{...snapshot,predictions:[]}});
assert.equal(missing.state,"incomplete");assert.equal(missing.rows.length,0);
const invalid=renderModel({mode:"public-preview",snapshot:{...snapshot,predictions:[...predictions,...predictions]}});
assert.equal(invalid.rows.length,0);
const unavailable=renderModel({mode:"public-preview",snapshot:undefined});
assert.equal(unavailable.rows.length,0);
assert.equal(JSON.stringify(unavailable).includes("TypeError"),false);
console.log("SECURITY-120 offline TV UI gate passed");
