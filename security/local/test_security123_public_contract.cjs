"use strict";
const assert=require("node:assert/strict");
const {prepare}=require("./security123-public-contract.cjs");
const {FIELDS}=require("./security113-tv-public-browser.js");
const {VERSION}=require("./security118-tv-freshness.cjs");
const base={metadata:[{game_id:2026020335,game_date:"2026-11-17",away_team:"EDM",home_team:"FLA",status:"pending",secret:"hidden"}],predictions:[{game_id:2026020335,core42_away:2,core42_home:3,core43_away:2.5,core43_home:3.5,core43_preview_away:2.6,core43_preview_home:3.4,away_gsax_per100:1.1,home_gsax_per100:null,private_token:"hidden"}],metadataAsOf:"2026-11-17T09:59:00Z",predictionsAsOf:"2026-11-17T09:59:00Z"};
const out=prepare(base);
assert.equal(out.version,VERSION);
assert.deepEqual(Object.keys(out.predictions[0]),FIELDS);
assert.equal(out.predictions[0].core43_home,3.5);
assert.equal(out.predictions[0].home_gsax_per100,null);
assert.equal(JSON.stringify(out).includes("hidden"),false);
assert.throws(()=>prepare({...base,predictions:[]}),/incomplete/);
assert.throws(()=>prepare({...base,predictions:[...base.predictions,...base.predictions]}),/duplicate/);
assert.throws(()=>prepare({...base,predictions:[{...base.predictions[0],game_id:9}]}),/orphan/);
assert.throws(()=>prepare({...base,predictions:[{...base.predictions[0],core42_away:Infinity}]}),/invalid/);
assert.throws(()=>prepare({...base,metadataAsOf:"not a date"}),/timestamp/);
assert.throws(()=>prepare({...base,version:"old"}),/version/);
console.log("SECURITY-123 narrow public TV contract passed");
